-- =============================================================================
-- 0015_drop_ticket_type_weight —— 人员类别不再有权重
-- =============================================================================
-- 背景：人员类别（ticket_types，A/B/C…）从此只决定发码数量，一码一票。
--   计分不再加权合并，「启用类别合计必须 100」的校验一并作废，因此列本身
--   没有存在理由，删列而不是留一列恒为 0 的死数据。
--
-- 依赖核查：weight_percent 无索引、无视图、无 CHECK、无生成列、无触发器引用
--   （0001_init 建表与索引清单已确认），故不写 CASCADE——将来若有人加了视图
--   依赖，让迁移显式失败（2BP01）好过静默连带删除视图。
--
-- 不可逆：原值丢失。回滚只能反向加回空列，历史占比无法恢复：
--   ALTER TABLE "ticket_types" ADD COLUMN "weight_percent" INTEGER NOT NULL DEFAULT 0;
-- 发布要求：迁移与新代码同版。旧代码 + 新库会因 SELECT weight_percent 报 42703。
-- =============================================================================

BEGIN;

-- 1) 删列（表内依赖由 PostgreSQL 自动连带处理）
ALTER TABLE "ticket_types" DROP COLUMN "weight_percent";

-- 2) 表注释同步新语义（原注释写的是「weight_percent 即占比，用于最终加权求和」）
COMMENT ON TABLE "ticket_types" IS '人员类别（A/B/C…）。只决定发码数量，不参与计分加权';

COMMIT;
