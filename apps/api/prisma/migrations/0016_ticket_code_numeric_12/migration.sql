-- =============================================================================
-- 0016_ticket_code_numeric_12 —— 随机码格式落到数据库（加固）
-- =============================================================================
-- 背景：随机码改为 12 位纯数字 0-9（含前导零，生成侧 padStart(12,'0')）。
--   应用层 lib/code.ts 是唯一生成入口，这一层 CHECK 只是兜底：防止将来绕过
--   生成入口写入手写 SQL / 一次性脚本时写出不合规的码。
--
-- NOT VALID 的用意：跳过全表扫描、立即提交。注意它只跳过**存量行**的初始
--   校验；后续 INSERT 与 UPDATE 仍会强制执行。因此旧 8 位码在迁移后虽然还能
--   登录（登录只查码），但核销（UPDATE status）与作废都会被 CHECK 拒绝
--   （23514，接口 500）——旧码既不能投票、也不能作废。
--   所以清空重发（人工运维，见 deploy/README.md §10）必须在 `db:deploy` 之后、
--   服务对外可用之前完成。清空后可选执行：
--   ALTER TABLE "tickets" VALIDATE CONSTRAINT "tickets_code_numeric_12_check";
--   该语句只取 SHARE UPDATE EXCLUSIVE 锁，不长时间阻塞读写。
--
-- 发布要求：必须与 lib/code.ts 的 12 位改动同版上线；旧代码写入 8 位码会在
--   CHECK 处失败（23514）。
-- =============================================================================

BEGIN;

-- 1) 码格式约束（NOT VALID：存量旧码不参与校验）
ALTER TABLE "tickets"
  ADD CONSTRAINT "tickets_code_numeric_12_check"
  CHECK ("code" ~ '^[0-9]{12}$') NOT VALID;

-- 2) 列注释同步新格式（原注释写的是「字符集剔除易混字符（无 O/0/I/1）」）
COMMENT ON COLUMN "tickets"."code" IS
  '随机码明文，全局唯一（跨场次不重复）；12 位纯数字 0-9，含前导零';

COMMIT;
